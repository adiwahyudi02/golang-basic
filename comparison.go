package main

import "fmt"

func main() {
	// comparison operator
	// > is greater than
	// < is less than
	// >= is greater than or equal to
	// <= is less than or equal to
	// == is equal to
	// != is not equal to

	fmt.Println("1 > 2 = ", 1 > 2)
	fmt.Println("1 < 2 = ", 1 < 2)
	fmt.Println("1 >= 2 = ", 1 >= 2)
	fmt.Println("1 <= 2 = ", 1 <= 2)
	fmt.Println("1 == 2 = ", 1 == 2)
	fmt.Println("1 != 2 = ", 1 != 2)
	fmt.Println("adi == adi = ", "adi" == "adi")
	fmt.Println("adi != wahyudi = ", "adi" != "wahyudi")
}