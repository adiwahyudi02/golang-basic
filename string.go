package main

import "fmt"

func main() {
	fmt.Println("Adi")
	fmt.Println("Wahyudi")

	// Function for string type
	// len("string") => length of string
	// "string"[index] => character at index, it will return byte
	fmt.Println(len("Adi"))
	fmt.Println("Adi"[0])
	fmt.Println("Adi"[1])
	fmt.Println("Adi"[2])
}